#!/usr/bin/env python3
"""Prototype 8 (GDD Edit 95): Dummy Corporation's text, from a Style Guide V2 run of the style loop.

  python3 prototypes/p8/make_lore.py style/runs/<id>-v8      # writes content/story/story_v2.json and prototypes/p8/lore.js

The run's v8_copy.json holds the accepted text (style/loop.py --v8). This script only places it:
  - story_v2.json: story.json with the 27 tales, three act lines, eleven briefs and the ending replaced. Every other field (orders,
    tasks, gifts, registry IDs) is copied unchanged, so the game plays as 7.13 does.
  - lore.js: window.DUMMIES_LORE (the interface notices, by id), window.DUMMIES_CREDITS (the one place Farsight is named), and the
    text patches Prototype 8 applies to the bundled content and fleet data before the game reads them.
"""
import copy
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RUN = Path(sys.argv[1]).resolve()
V8 = json.loads((RUN / "v8_copy.json").read_text(encoding="utf-8"))
STORY = json.loads((ROOT / "content" / "story" / "story.json").read_text(encoding="utf-8"))

not_accepted = [k for k, v in V8["accepted"].items() if not v]
if not_accepted:
    sys.exit("not accepted at 10/10 in " + RUN.name + ": " + ", ".join(not_accepted))

s = copy.deepcopy(STORY)
s["meta"]["version"] = "edit95-2026-10-29"
s["meta"]["status"] = ("Narrative A, Certified, under the lore refinement of GDD Edit 95 (user-decided, 29 October): Dummy Corporation narrates; "
                       "Farsight, the publisher, is named only in the Credits. Text from style run " + RUN.name + " on Style Guide V2; gameplay fields as story.json (edit93)")
s["meta"]["consumers"] = ["prototypes/p8 (story.js, game.js): Prototype 8"]
s["meta"]["sources"] = s["meta"]["sources"] + ["GDD Edit 95: lore refinement, Dummy Corporation", "style/STYLE_GUIDE_V2.md; style run " + RUN.name]
s["meta"]["rules"] = [r for r in s["meta"]["rules"] if not r.startswith("Edit 92:")] + [
    "Edit 92: Narrative A, Certified. Act I Monument (Induction), Act II Parkland (Opening Day), Act III Waterfront (Customs).",
    "Edit 95: Dummy Corporation narrates: deadpan and inspirational, few adjectives, no exclamation marks. Every text at most two sentences and 20 words (style.v2.text.maxSentences, style.v2.text.maxWords). Farsight is named only in the Credits.",
]
for d in s["districts"]:
    d["intro"] = V8["acts"][d["id"]]
    for t, tile in d["tiles"].items():
        tile["tale"] = V8["tales"][d["id"]][t]
for k, b in V8["briefs"].items():
    s["tasks"][k]["label"], s["tasks"][k]["brief"] = b["label"], b["brief"]
s["ending"] = V8["ending"]
(ROOT / "content" / "story" / "story_v2.json").write_text(json.dumps(s, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")

N = V8["notices"]
lore = {"build": "P8", "edit": 95, "run": RUN.name, "notices": N}
credits = {"lines": V8["credits"]}
patch = {
    "content": {"interface.copy.toast.drone-dispatch": N["n18"], "interface.copy.toast.rescue-dispatch": N["n17"], "interface.copy.toast.rescued": N["n19"],
                "interface.copy.endings.Licensed": N["n20"], "interface.copy.endings.Failed test": N["n21"], "terminal.title.lines.0": N["n02"]},
    "barks": V8["barks"],
    "canon": {"company": "Dummy Corporation", "publisher": "Farsight (extra-diegetic; the Credits only)"},
}
js = f"""// Prototype 8 (GDD Edit 95): Dummy Corporation's text. Generated by prototypes/p8/make_lore.py from style run {RUN.name}
// (style/loop.py --v8, Style Guide V2). Edit the run, not this file. Loaded after content.js and the fleet database, before game.js.
window.DUMMIES_LORE = {json.dumps(lore, indent=1, ensure_ascii=False)};
window.DUMMIES_CREDITS = {json.dumps(credits, indent=1, ensure_ascii=False)};
(function (P) {{
  const set = (root, path, v) => {{ const k = path.split('.'); let o = root; for (const p of k.slice(0, -1)) {{ if (!o) return; if (o[p] == null) o[p] = {{}}; o = o[p]; }} if (o) o[k[k.length - 1]] = v; }};
  if (window.DUMMIES_CONTENT) for (const [path, v] of Object.entries(P.content)) set(window.DUMMIES_CONTENT, path, v);
  const F = window.FLEET_DB;
  if (F) {{
    for (const b of F.barks) if (P.barks[b.id]) Object.assign(b, P.barks[b.id]);
    Object.assign(F.canon, P.canon);
  }}
}})({json.dumps(patch, indent=1, ensure_ascii=False)});
"""
(ROOT / "prototypes" / "p8" / "lore.js").write_text(js, encoding="utf-8")
print("story_v2.json and lore.js from", RUN.name, "·", len(N), "notices ·", len(V8["barks"]), "barks ·", sum(len(v) for v in V8["tales"].values()), "tales")
